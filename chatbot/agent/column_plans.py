def list_domains() -> List[str]:
    return sorted(DOMAIN_MAIN_COLUMNS.keys())


def main_columns_for(domain: str) -> List[str]:
    return list(DOMAIN_MAIN_COLUMNS.get(domain, []))


def prompt_block() -> str:
    """Compact plan text for LLM system prompts."""
    lines = [
        "DISPLAY COLUMN RULES (chatbot shows MAIN columns only, not full table dumps):",
    ]
    for domain, cols in DOMAIN_MAIN_COLUMNS.items():
        lines.append(f"- {domain}: {', '.join(cols[:8])}{'…' if len(cols) > 8 else ''}")
    lines.append(
        "When writing SELECT, prefer these aliases. Do not SELECT every column "
        "(skip ids, timestamps, internal FKs unless asked)."
    )
    return "\n".join(lines)
